TEXT_BRIGHT = "#e8f6ff"
TEXT_DIM = "#7aa0c0"
HOVER = "#2ab0e0"


def button_svg(glyph_active: str, glyph_inactive: str) -> str:
    """Eight Aurorae button states on a 24×24 grid, strip width 192."""
    states = [
        ("active-center", None, BASE, glyph_active),
        ("hover-center", "translate(24,0)", HOVER, glyph_active),
        ("pressed-center", "translate(48,0)", BASE, glyph_active),
        ("inactive-center", "translate(72,0)", ACCENT, glyph_inactive),
        ("deactivated-center", "translate(96,0)", BG, glyph_inactive),
        ("hover-inactive-center", "translate(120,0)", ACCENT, glyph_inactive),
        ("pressed-inactive-center", "translate(144,0)", BG, glyph_inactive),
        ("deactivated-inactive-center", "translate(168,0)", BG, glyph_inactive),
    ]
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<svg xmlns="http://www.w3.org/2000/svg" width="192" height="24" version="1.1">',
        "  <!-- Generated by tools/generate-aurorae.py — do not hand-edit. -->",
    ]
    for sid, transform, tile, glyph in states:
        tr = f' transform="{transform}"' if transform else ""
        parts.append(f'  <g id="{sid}"{tr}>')
        parts.append(
            f'    <rect x="0" y="0" width="24" height="24" fill="{tile}"/>'
        )
        for line in glyph.strip().splitlines():
            parts.append(f"    {line.strip()}")
        parts.append("  </g>")
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


