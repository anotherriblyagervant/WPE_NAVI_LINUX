"""Generate Copland LAIN Aurorae SVG theme assets.

Edit the palette / glyphs here, then run from the repo root:

    python3 tools/generate-aurorae.py

Committed SVGs under packages/aurorae/themes/org.lainavi.copland/ are what
KWin installs — this script is the single edit path so the nine button files
and decoration.svg stay in sync.

Fills are hardcoded scene hexes (not Plasma ColorScheme classes). ColorScheme
remapping previously turned inactive chrome white; brand chrome must stay
locked to the wallpaper palette regardless of the active scheme.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / "packages/aurorae/themes/org.lainavi.copland"
VERSION = "1.2"

# Scene palette (match packages/plasma/.../scene/css/scene.css)
